"""Pin XML Schema regex word categories to Unicode 16 for reproducible builds."""

from __future__ import annotations

import unicodedata
from pathlib import Path
from typing import Final


def main() -> None:
    """Write the word category table for the XSD regex matcher."""
    unicode_version: Final = "16.0.0"
    if unicodedata.unidata_version != unicode_version:
        msg = f"Unicode {unicode_version} is required; found {unicodedata.unidata_version}"
        raise RuntimeError(msg)

    pages: list[int] = []
    mixed: list[list[int]] = []
    for page in range(0x1100):
        bits = [
            sum(
                1 << offset
                for offset in range(64)
                if unicodedata.category(chr(page * 256 + word * 64 + offset))[0] not in "PZC"
            )
            for word in range(4)
        ]
        if all(word == 0 for word in bits):
            pages.append(0)
        elif all(word == 0xFFFFFFFFFFFFFFFF for word in bits):
            pages.append(1)
        else:
            pages.append(len(mixed) + 2)
            mixed.append(bits)
    if len(mixed) > 254:
        message: Final = "more than 254 mixed pages need a wider page index"
        raise RuntimeError(message)

    page_rows = [
        "    " + ", ".join(str(kind) for kind in pages[index : index + 32]) + "," for index in range(0, len(pages), 32)
    ]
    mixed_rows = ["    {" + ", ".join(f"0x{word:016X}u" for word in bits) + "}," for bits in mixed]
    (Path(__file__).resolve().parents[1] / "src/turbohtml/_c/data/xsd_word_table.h").write_text(
        "/* Auto-generated by tools/generate_xsd_word.py - do not edit. */\n"
        f"/* Unicode {unicode_version} categories except P, Z, and C (XML Schema regex \\w). */\n\n"
        "#ifndef TURBOHTML_XSD_WORD_TABLE_H\n#define TURBOHTML_XSD_WORD_TABLE_H\n\n"
        "#include <stdint.h>\n\n"
        f"static const uint64_t TH_WORD_ASCII_BITS[2] = {{0x{mixed[pages[0] - 2][0]:016X}u, "
        f"0x{mixed[pages[0] - 2][1]:016X}u}};\n\n"
        "static const uint8_t TH_WORD_PAGE_KIND[0x1100] = {\n"
        + "\n".join(page_rows)
        + "\n};\n\nstatic const uint64_t TH_WORD_MIXED_BITS[][4] = {\n"
        + "\n".join(mixed_rows)
        + "\n};\n\n#endif /* TURBOHTML_XSD_WORD_TABLE_H */\n"
    )


if __name__ == "__main__":
    main()
