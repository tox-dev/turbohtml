"""Pin XML Schema regex categories to Unicode 16 for reproducible builds."""

from __future__ import annotations

import unicodedata
from pathlib import Path
from typing import Final

CATEGORIES: Final[tuple[str, ...]] = (
    "Cc",
    "Cf",
    "Cn",
    "Co",
    "Cs",
    "Ll",
    "Lm",
    "Lo",
    "Lt",
    "Lu",
    "Mc",
    "Me",
    "Mn",
    "Nd",
    "Nl",
    "No",
    "Pc",
    "Pd",
    "Pe",
    "Pf",
    "Pi",
    "Po",
    "Ps",
    "Sc",
    "Sk",
    "Sm",
    "So",
    "Zl",
    "Zp",
    "Zs",
)


def main() -> None:
    """Write Unicode property tables for the XSD regex matcher."""
    unicode_version: Final = "16.0.0"
    if unicodedata.unidata_version != unicode_version:
        msg = f"Unicode {unicode_version} is required; found {unicodedata.unidata_version}"
        raise RuntimeError(msg)

    word_pages: Final[list[int]] = []
    word_mixed: Final[list[list[int]]] = []
    digit_pages: Final[list[int]] = []
    digit_mixed: Final[list[list[int]]] = []
    category_pages: Final[list[int]] = []
    category_mixed: Final[list[list[int]]] = []
    category_ids: Final[dict[str, int]] = {name: index for index, name in enumerate(CATEGORIES)}
    for page in range(0x1100):
        categories = [unicodedata.category(chr(page * 256 + offset)) for offset in range(256)]
        category_values = [category_ids[category] for category in categories]
        if all(category == category_values[0] for category in category_values):
            category_pages.append(category_values[0])
        else:
            category_pages.append(len(CATEGORIES) + len(category_mixed))
            category_mixed.append(category_values)
        word_bits = [
            sum(1 << offset for offset in range(64) if categories[word * 64 + offset][0] not in "PZC")
            for word in range(4)
        ]
        digit_bits = [
            sum(1 << offset for offset in range(64) if categories[word * 64 + offset] == "Nd") for word in range(4)
        ]
        _append_page(word_bits, word_pages, word_mixed)
        _append_page(digit_bits, digit_pages, digit_mixed)

    _write_table(
        "WORD", "categories except P, Z, and C (XML Schema regex \\w)", word_pages, word_mixed, unicode_version
    )
    _write_table("DIGIT", "category Nd (XML Schema regex \\d)", digit_pages, digit_mixed, unicode_version)
    _write_category_table(category_pages, category_mixed, unicode_version)
    _write_block_table(unicode_version)


def _append_page(bits: list[int], pages: list[int], mixed: list[list[int]]) -> None:
    if all(word == 0 for word in bits):
        pages.append(0)
    elif all(word == 0xFFFFFFFFFFFFFFFF for word in bits):
        pages.append(1)
    else:
        pages.append(len(mixed) + 2)
        mixed.append(bits)


def _write_table(kind: str, description: str, pages: list[int], mixed: list[list[int]], unicode_version: str) -> None:
    if len(mixed) > 254:
        message: Final = "more than 254 mixed pages need a wider page index"
        raise RuntimeError(message)

    page_rows = [
        "    " + ", ".join(str(page) for page in pages[index : index + 32]) + "," for index in range(0, len(pages), 32)
    ]
    mixed_rows = ["    {" + ", ".join(f"0x{word:016X}u" for word in bits) + "}," for bits in mixed]
    ascii_bits = (
        f"static const uint64_t TH_WORD_ASCII_BITS[2] = {{0x{mixed[pages[0] - 2][0]:016X}u, "
        f"0x{mixed[pages[0] - 2][1]:016X}u}};\n\n"
        if kind == "WORD"
        else ""
    )
    (Path(__file__).resolve().parents[1] / f"src/turbohtml/_c/data/xsd_{kind.lower()}_table.h").write_text(
        "/* Auto-generated by tools/generate_xsd_categories.py - do not edit. */\n"
        f"/* Unicode {unicode_version} {description}. */\n\n"
        f"#ifndef TURBOHTML_XSD_{kind}_TABLE_H\n#define TURBOHTML_XSD_{kind}_TABLE_H\n\n"
        "#include <stdint.h>\n\n"
        + ascii_bits
        + f"static const uint8_t TH_{kind}_PAGE_KIND[0x1100] = {{\n"
        + "\n".join(page_rows)
        + f"\n}};\n\nstatic const uint64_t TH_{kind}_MIXED_BITS[][4] = {{\n"
        + "\n".join(mixed_rows)
        + f"\n}};\n\n#endif /* TURBOHTML_XSD_{kind}_TABLE_H */\n"
    )


def _write_category_table(pages: list[int], mixed: list[list[int]], unicode_version: str) -> None:
    page_rows = [
        "    " + ", ".join(str(page) for page in pages[index : index + 32]) + "," for index in range(0, len(pages), 32)
    ]
    mixed_rows = ["    {" + ", ".join(str(category) for category in values) + "}," for values in mixed]
    (Path(__file__).resolve().parents[1] / "src/turbohtml/_c/data/xsd_category_table.h").write_text(
        "/* Auto-generated by tools/generate_xsd_categories.py - do not edit. */\n"
        f"/* Unicode {unicode_version} general categories (XML Schema regex \\p and \\P). */\n\n"
        "#ifndef TURBOHTML_XSD_CATEGORY_TABLE_H\n#define TURBOHTML_XSD_CATEGORY_TABLE_H\n\n"
        "#include <stdint.h>\n\n"
        "static const char *const TH_CATEGORY_NAMES[] = {" + ", ".join(f'"{name}"' for name in CATEGORIES) + "};\n\n"
        "static const uint16_t TH_CATEGORY_PAGE_KIND[0x1100] = {\n"
        + "\n".join(page_rows)
        + "\n};\n\nstatic const uint8_t TH_CATEGORY_MIXED[][256] = {\n"
        + "\n".join(mixed_rows)
        + "\n};\n\n#endif /* TURBOHTML_XSD_CATEGORY_TABLE_H */\n"
    )


def _write_block_table(unicode_version: str) -> None:
    block_rows: Final[list[str]] = []
    modern_names: Final[set[str]] = set()
    for version in (unicode_version, "3.1.0"):
        for line in Path(__file__).with_name(f"Blocks-{version}.txt").read_text().splitlines():
            if not line or line.startswith("#"):
                continue
            extent, name = line.split(";", 1)
            block_name = "".join(name.split())
            if version == unicode_version:
                modern_names.add(block_name)
            elif block_name in modern_names:
                continue
            start, end = extent.strip().split("..", 1)
            block_rows.append(f'    {{"{block_name}", 0x{start}u, 0x{end}u}},')

    (Path(__file__).resolve().parents[1] / "src/turbohtml/_c/data/xsd_block_table.h").write_text(
        "/* Auto-generated by tools/generate_xsd_categories.py - do not edit. */\n"
        f"/* Unicode {unicode_version} Blocks.txt ranges and Unicode 3.1 aliases (XML Schema regex IsBlock). */\n\n"
        "#ifndef TURBOHTML_XSD_BLOCK_TABLE_H\n#define TURBOHTML_XSD_BLOCK_TABLE_H\n\n"
        "#include <stdint.h>\n\n"
        "typedef struct { const char *name; uint32_t lo, hi; } th_xsd_block;\n\n"
        "static const th_xsd_block TH_XSD_BLOCKS[] = {\n"
        + "\n".join(block_rows)
        + "\n};\n\n#endif /* TURBOHTML_XSD_BLOCK_TABLE_H */\n"
    )


if __name__ == "__main__":
    main()
